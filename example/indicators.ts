/**
 * THE VENDOR'S NUMBERS, TURNED INTO THIS DOMAIN'S POINTS — and every line of it is here, in the
 * host, because the package may not hold any of it.
 *
 * `lightweight-charts-indicators` is 1.05 MB of arithmetic and 320 offered names. `src/` gains none
 * of it: `test/boundary.spec.ts` bans the specifier and the entry's byte ceiling would refuse the
 * bytes anyway. What crosses the seam is what this file produces — a `PlottableSource` per chosen
 * study, and a plain value per control the workspace stores and never reads.
 *
 * ── EVERY POINT IS BUILT FROM THE BAR INDEX, AND THAT IS A DEFENCE, NOT A STYLE ────────────────
 *
 * The timestamp is the HOST's; only the value is the vendor's. `src/indicator/availability.ts`
 * aligns by timestamp with LAST WRITE WINNING, so a point the vendor stamps with a neighbour's bar
 * time is not discarded as off-grid — it OVERWRITES the reading that belongs to that neighbour.
 * `double-macd` does exactly that, two bars back, which is why the catalogue excludes it; but
 * excluding one entry treats one symptom. Reading the time off `bars[index]` removes the vector for
 * all of them at once, and it is sound because full-length index alignment is measured rather than
 * hoped for: 457/457 across the registry.
 *
 * ── A VALUE THAT IS NOT A NUMBER IS A DECLARED GAP, NEVER A ZERO ───────────────────────────────
 *
 * The vendor marks its warm-up with `NaN` and, on short windows, with `null`. This domain says a
 * `Point` WITHOUT `value` is a gap and draws nothing there, while a zero is a reading — the loudest
 * possible mark for the emptiest possible reason. `readingOf` already reads a non-finite as `null`,
 * so the conversion belongs where the vendor's shape is translated, which is here.
 *
 * ── THE PLOT KEY COMES FROM THE MANIFEST, WHICH READ IT OFF `plotConfig` ───────────────────────
 *
 * 42 of the 320 offered entries carry a key that is not `plotN` — `trendLine`, `exitLine`, `plotU`.
 * Assuming `plot0` would draw a quarter of the catalogue as an empty lane. The manifest carries the
 * keys the vendor declares and does not hide, and this file draws those and only those.
 *
 * ── THE `unknown` IS NARROWED HERE ─────────────────────────────────────────────────────────────
 *
 * `StudySettings` is `unknown` on purpose: the compiler refuses the package a property read, which
 * is what keeps the vendor's vocabulary out of `src/`. The narrowing is the host's obligation, and
 * it REFUSES an out-of-range value rather than clamping it — a value silently rewritten is a value
 * the user did not choose, arriving back on every load.
 */
